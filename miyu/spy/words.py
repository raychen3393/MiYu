DIFF_NAME = {0: "全部", 1: "简单", 2: "普通", 3: "困难"}


def all_pairs(category: str = "全部", diff: int = 0) -> list[tuple[str, str, int]]:
    cats = CATEGORIES.values() if category not in CATEGORIES else [CATEGORIES[category]]
    out = [p for c in cats for p in c if diff == 0 or p[2] == diff]
    return out or [p for c in CATEGORIES.values() for p in c]


def pick(category: str = "全部", diff: int = 0, rng: random.Random | None = None,
         avoid: set | None = None) -> tuple[str, str]:
    """挑一对词,随机决定哪个给平民(返回 (平民词, 卧底词))。avoid:最近玩过的,尽量不重复。"""
    rng = rng or random.Random()
    pairs = all_pairs(category, diff)
    fresh = [p for p in pairs if (p[0], p[1]) not in (avoid or set())] or pairs
    a, b, _d = rng.choice(fresh)
    return (a, b) if rng.random() < 0.5 else (b, a)


def count() -> int:
    return sum(len(v) for v in CATEGORIES.values())
