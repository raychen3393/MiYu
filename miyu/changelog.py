MAX_ITEMS, MAX_ITEM_LEN = 12, 120            # 收别人发来的更新内容时的上限


def entry(version: str):
    for e in CHANGELOG:
        if e[0] == version:
            return e
    return None


def notes_between(old: str, new: str, log=None) -> list:
    """比 old 新、不比 new 新的那些版本(新的在前)。"""
    log = CHANGELOG if log is None else log
    return [e for e in log if newer(e[0], old) and not newer(e[0], new)]


def format_entries(entries) -> str:
    out = []
    for v, date, items in entries:
        out.append(f"v{v}" + (f"  ·  {date}" if date else ""))
        out += [f"  • {x}" for x in items]
    return "\n".join(out)


def to_wire(limit: int = 6) -> list:
    """跟着版本号一起发给别人的更新内容(最近几个版本)。"""
    return [[v, d, list(items)] for v, d, items in CHANGELOG[:limit]]


def from_wire(data) -> list:
    """收到的更新内容:只留格式正确的,文字截短(这部分不在签名里,只是给人看的说明)。"""
    out = []
    if not isinstance(data, list):
        return out
    for e in data[:10]:
        if not (isinstance(e, list) and len(e) == 3 and valid_version(e[0]) and isinstance(e[2], list)):
            continue
        date = e[1] if isinstance(e[1], str) and len(e[1]) <= 10 else ""
        items = [" ".join(x.split())[:MAX_ITEM_LEN] for x in e[2][:MAX_ITEMS] if isinstance(x, str) and x.strip()]
        if items:
            out.append((e[0], date, items))
    return out
